const DICTS: Record<Lang, Dict> = { de, en, ro, tr, pl, hr, bg };

export function t(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ''));
}

/** Alle Sprachen haben dieselben Schlüssel wie Deutsch (für den Test). */
export function missingKeys(): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const [l, d] of Object.entries(DICTS)) {
    const miss = Object.keys(de).filter((k) => !(k in d));
    if (miss.length) out[l] = miss;
  }
  return out;
}

